const norm = (s: string) => s.toLowerCase().replaceAll('ё', 'е').replace(/\s+/g, ' ').trim()

/** Подсказки: сначала города, начинающиеся с запроса, затем содержащие его; пустой запрос — популярные. */
export function suggestCities(query: string, limit = 8): string[] {
  const q = norm(query)
  if (!q) return cities.slice(0, limit)
  const starts: string[] = []
  const inside: string[] = []
  for (const c of cities) {
    const n = norm(c)
    if (n.startsWith(q)) starts.push(c)
    else if (n.split(/[\s-]/).some((w) => w.startsWith(q))) inside.push(c)
  }
  return [...starts, ...inside].slice(0, limit)
}
